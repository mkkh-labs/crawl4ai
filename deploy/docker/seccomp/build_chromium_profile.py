#!/usr/bin/env python3
"""
Build deploy/docker/seccomp/chromium.json from Docker's default seccomp profile.

Chromium's renderer sandbox needs unprivileged user, PID and network
namespaces and a chroot. Docker's default profile allows clone() only
without namespace flags, and gates unshare()/chroot() behind
CAP_SYS_ADMIN/CAP_SYS_CHROOT, which this container drops. So Chromium could
only run with --no-sandbox.

This adds the narrowest rules that let the sandbox start, and nothing else:

* clone(2) / unshare(2) whose namespace flags are a non-empty subset of
  USER|PID|NET. Mount, UTS, IPC and cgroup namespaces stay denied: the
  masked-equality match fails for any set that includes them.
* chroot(2): Chromium chroots its zygote inside the new user namespace. In
  the initial namespace the call still fails, because the container has no
  CAP_SYS_CHROOT.
* socket(AF_NETLINK, *, NETLINK_NETFILTER) -> EPERM. Unprivileged user +
  network namespaces expose nf_tables, the most exploited path from a
  userns to the kernel. Chromium does not use netfilter netlink. ERRNO
  outranks ALLOW in libseccomp, so this holds despite the generic socket
  allow.

Usage: build_chromium_profile.py <docker default.json> <out chromium.json>
The default.json source and hash are recorded in the output's comment field.
"""

from __future__ import annotations

import hashlib
import json
import sys

CLONE_NEWUSER = 0x10000000
CLONE_NEWPID = 0x20000000
CLONE_NEWNET = 0x40000000
# Every namespace flag (NEWNS|NEWCGROUP|NEWUTS|NEWIPC|NEWUSER|NEWPID|NEWNET):
# the same mask Docker's default profile uses for clone.
NS_MASK = 0x7E020000
# Every non-empty combination of USER, PID and NET. Chromium creates its
# sandbox with USER|PID|NET, and its zygote then forks each renderer into a
# fresh PID namespace (PID alone). Without CAP_SYS_ADMIN, PID/NET-only
# namespaces can be created only inside a user namespace the caller owns.
_ALLOWED = (CLONE_NEWUSER, CLONE_NEWPID, CLONE_NEWNET)
CHROMIUM_NS_SETS = tuple(
    sum(flag for bit, flag in enumerate(_ALLOWED) if combo >> bit & 1)
    for combo in range(1, 1 << len(_ALLOWED))
)
AF_NETLINK = 16
NETLINK_NETFILTER = 12


def _ns_rule(name: str, arg_index: int, value: int) -> dict:
    return {
        "names": [name],
        "action": "SCMP_ACT_ALLOW",
        "args": [
            {
                "index": arg_index,
                "value": NS_MASK,
                "valueTwo": value,
                "op": "SCMP_CMP_MASKED_EQ",
            }
        ],
        "comment": "chromium namespace sandbox",
        "excludes": {"arches": ["s390", "s390x"]} if name == "clone" else {},
    }


def build(default: dict) -> dict:
    profile = json.loads(json.dumps(default))
    extra = []
    for value in CHROMIUM_NS_SETS:
        extra.append(_ns_rule("clone", 0, value))
        extra.append(_ns_rule("unshare", 0, value))
    extra.append(
        {
            "names": ["chroot"],
            "action": "SCMP_ACT_ALLOW",
            "args": [],
            "comment": "chromium zygote chroot (only effective inside its userns)",
            "includes": {},
            "excludes": {},
        }
    )
    extra.append(
        {
            "names": ["socket"],
            "action": "SCMP_ACT_ERRNO",
            "errnoRet": 1,
            "args": [
                {"index": 0, "value": AF_NETLINK, "op": "SCMP_CMP_EQ"},
                {"index": 2, "value": NETLINK_NETFILTER, "op": "SCMP_CMP_EQ"},
            ],
            "comment": "deny nf_tables from inside user namespaces",
            "includes": {},
            "excludes": {},
        }
    )
    profile["syscalls"].extend(extra)
    return profile


def main(argv: list[str]) -> int:
    src, out = argv[1], argv[2]
    raw = open(src, "rb").read()
    profile = build(json.loads(raw))
    profile["comment"] = (
        "Generated by deploy/docker/seccomp/build_chromium_profile.py from "
        "moby default.json sha256:" + hashlib.sha256(raw).hexdigest()
    )
    with open(out, "w") as fh:
        json.dump(profile, fh, indent=2)
        fh.write("\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
